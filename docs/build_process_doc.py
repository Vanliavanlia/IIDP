d.p("· 再用 JSON 手写 filter 查询报 Invalid leaf，说明过滤语法不对；转为在 Java 代码里用 Filter 构造，仍为 0 行。")
d.p("· 怀疑 iam 对普通用户做了行级数据权限（组织 / 租户限制），导致跨应用查询 rbac_user 被过滤。")
d.p("· 用 javap 查看引擎的 Meta 类（com.sie.snest.engine.container.Meta），发现提供 getUserId()、getUser()、"
    "getUserName() 等会话 API，可直接取当前用户，无需查 rbac_user。")

d.h("解决方案", 3)
d.code([
    "private String loginOfCurrentUser() {",
    "    String login = getMeta().getUser() == null ? null : getMeta().getUser().getStr(\"login\");",
    "    if (login == null || login.trim().isEmpty()) {",
    "        // 退化为显示名匹配（getUserName 返回的是显示名）",
    "        login = getMeta().getUserName();",
    "    }",
    "    return login;",
    "}",
    "// 绑定关系按「登录名或姓名」双条件匹配",
    "Filter f = Filter.AND(",
    "    Filter.OR(Filter.equal(\"userLogin\", login), Filter.equal(\"userName\", displayName)),",
    "    Filter.equal(\"status\", \"enabled\"));",
])

